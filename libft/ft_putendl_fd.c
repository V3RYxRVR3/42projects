void	ft_putendl_fd(char *s, int fd)
{
	int i;

	i = 0;
	if (s[i] == NULL)
		return ;
	while (s[i] != '\0')
	{
		write (fd, &s[i], 1);
		i++;
	}
	write (fd, "\n", 1);
}
